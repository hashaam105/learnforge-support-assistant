def _find_retired_leaks(answer: str, deprecated_claims: list[dict[str, Any]]) -> list[str]:
    """Detect a withdrawn statement being presented as current.

    We look for the claim's *salient* tokens — the numbers-with-units and the
    handful of named things that make a retired rule identifiable ("7 days",
    "five quizzes", "Internet Explorer") — rather than matching the sentence,
    because the model paraphrases. A hit only counts if there is no retirement
    marker nearby, so "LearnForge no longer treats the 7-day period as
    current" passes while "you have 7 days to request a refund" does not.
    """
    leaks: list[str] = []
    for claim in deprecated_claims:
        text = claim.get("claim_text", "")
        tokens = {f"{m.group(1)} {m.group(2).lower()}" for m in _SALIENT.finditer(text)}
        tokens |= {m.group(0).lower() for m in _PROPER_NOUN.finditer(text)}
        for token in tokens:
            for position in _find_token(answer, token):
                window = answer[
                    max(0, position - _MARKER_WINDOW) : position + _MARKER_WINDOW
                ]
                if not _RETIREMENT_MARKERS.search(window):
                    leaks.append(f"{claim['doc_id']}: '{token}' asserted as current")
                    break
            else:
                continue
            break
    return sorted(set(leaks))


def _find_token(answer: str, token: str) -> list[int]:
    """Positions of a '<number> <unit>' or phrase token, allowing '7-day'."""
    parts = token.split(" ", 1)
    if len(parts) == 2 and parts[0].isdigit():
        number, unit = parts
        pattern = rf"\b{re.escape(number)}[-\s]?{re.escape(unit.rstrip('s'))}s?\b"
    else:
        pattern = re.escape(token)
    return [m.start() for m in re.finditer(pattern, answer, re.I)]


def _looks_factual(answer: str) -> bool:
    """Does this answer make claims that ought to be cited?

    A pure clarifying question or a handoff message has nothing to cite, and
    flagging it as uncited would punish exactly the behaviour we want.
    """
    stripped = answer.strip()
    if stripped.endswith("?") and len(stripped.split()) < 40:
        return False
    return len(stripped.split()) > 15


def _as_float(value: Any, *, default: float) -> float:
    try:
        return float(value)
    except (TypeError, ValueError):
        return default
